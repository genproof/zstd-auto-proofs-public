// Writes harness/corpus.h: real frames for env.c (native and interpreter runs), made by the upstream
// compressor (patch/gen_corpus.sh).  Each frame fits SRC_MAX = 4096 bytes and decodes to at most 3000.
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define ZSTD_STATIC_LINKING_ONLY
#include "zstd.h"

static FILE *out;
static int count;
static unsigned long long s = 1;
static unsigned rnd(void) { s = s * 6364136223846793005ULL + 1442695040888963407ULL; return (unsigned) (s >> 33); }

static void emit(const char *what, const unsigned char *p, size_t n, size_t content)
{
	fprintf(out, "/* %s */\nstatic const unsigned char corpus%d[%zu] = {", what, count, n ? n : 1);
	for (size_t i = 0; i < n; i++)
		fprintf(out, "%s%s%u", i ? "," : "", i % 24 ? "" : "\n  ", p[i]);
	fprintf(out, "%s};\n", n ? "" : "0");
	fprintf(out, "#define corpus%d_len %zu\n#define corpus%d_content %zu\n", count, n, count, content);
	count++;
}

static size_t comp(unsigned char *dst, const unsigned char *src, size_t n, int level, int checksum, int csize)
{
	ZSTD_CCtx *c = ZSTD_createCCtx();
	ZSTD_CCtx_setParameter(c, ZSTD_c_compressionLevel, level);
	ZSTD_CCtx_setParameter(c, ZSTD_c_checksumFlag, checksum);
	ZSTD_CCtx_setParameter(c, ZSTD_c_contentSizeFlag, csize);
	size_t r = ZSTD_compress2(c, dst, 4096, src, n);
	ZSTD_freeCCtx(c);
	if (ZSTD_isError(r)) { fprintf(stderr, "%s\n", ZSTD_getErrorName(r)); exit(1); }
	return r;
}

int main(void)
{
	static unsigned char text[3000], b[3000], f[4096];
	const char *w[] = { "frame ", "block ", "literal ", "match ", "offset ", "huffman ", "sequence " };
	for (size_t i = 0; i < sizeof text;) {
		const char *x = w[rnd() % 7];
		for (size_t k = 0; x[k] && i < sizeof text; k++) text[i++] = (unsigned char) x[k];
	}
	out = fopen("harness/corpus.h", "w");
	fprintf(out, "// Real zstd frames for env.c, generated by patch/gen_corpus.sh (upstream compressor).\n");
	size_t m;
	m = comp(f, text, 0, 3, 0, 1);        emit("empty input", f, m, 0);
	m = comp(f, text, 1, 3, 0, 1);        emit("one byte (raw block)", f, m, 1);
	m = comp(f, text, 120, 3, 1, 1);      emit("120 bytes of text, checksum", f, m, 120);
	m = comp(f, text, 3000, 1, 0, 1);     emit("3000 bytes of text, level 1", f, m, 3000);
	m = comp(f, text, 3000, 19, 1, 1);    emit("3000 bytes of text, level 19, checksum", f, m, 3000);
	m = comp(f, text, 2000, -5, 0, 0);    emit("2000 bytes of text, negative level, no content size", f, m, 2000);
	memset(b, 'z', 3000);
	m = comp(f, b, 3000, 3, 0, 1);        emit("3000 x 'z' (RLE)", f, m, 3000);
	for (int i = 0; i < 1500; i++) b[i] = (unsigned char) rnd();
	m = comp(f, b, 1500, 3, 1, 1);        emit("1500 random bytes (raw block), checksum", f, m, 1500);
	for (int i = 0; i < 3000; i++) b[i] = i % 9 == 0 ? (unsigned char) rnd() : (unsigned char) "abcdefgh"[i % 8];
	m = comp(f, b, 3000, 6, 0, 1);        emit("3000 bytes, periodic with noise, level 6", f, m, 3000);
	for (int i = 0; i < 2500; i++) b[i] = (unsigned char) ("ACGT"[rnd() % 4]);
	m = comp(f, b, 2500, 9, 0, 1);        emit("2500 bytes over a 4-letter alphabet (Huffman literals)", f, m, 2500);
	size_t m1 = comp(f, text, 300, 3, 0, 1);
	size_t m2 = comp(f + m1, text + 300, 400, 5, 1, 1);
	size_t m3 = ZSTD_writeSkippableFrame(f + m1 + m2, 64, "skip", 4, 7);
	emit("two frames and a skippable frame", f, m1 + m2 + m3, 700);
	fprintf(out, "static const unsigned char *const corpus[] = {");
	for (int i = 0; i < count; i++) fprintf(out, "%scorpus%d", i ? ", " : "", i);
	fprintf(out, "};\nstatic const unsigned long corpus_len[] = {");
	for (int i = 0; i < count; i++) fprintf(out, "%scorpus%d_len", i ? ", " : "", i);
	fprintf(out, "};\nstatic const unsigned long corpus_content[] = {");
	for (int i = 0; i < count; i++) fprintf(out, "%scorpus%d_content", i ? ", " : "", i);
	fprintf(out, "};\n#define CORPUS_N %d\n", count);
	fclose(out);
	printf("harness/corpus.h: %d frames\n", count);
	return 0;
}
