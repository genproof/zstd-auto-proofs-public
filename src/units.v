(* CONTRACT: the units of the code under test, generated by quickproof/tools/new_contract.py.
   Each unit's `prog` is the clightgen output (quickproof/tools/clight.sh), never edited by hand,
   lifted to a QP.program; the lift needs the unit's own compspecs, hence one module per unit. *)
