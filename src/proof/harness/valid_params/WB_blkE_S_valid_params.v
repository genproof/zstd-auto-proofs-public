Lemma blkS_join {cs: compspecs} n m sh t (v1 v2: list (reptype t)) p :
  Zlength v1 = n -> Zlength v2 = m - n ->
  data_at sh (tarray t n) v1 p * data_at sh (tarray t (m - n)) v2 (field_address0 (tarray t m) (SUB n) p)
  |-- data_at sh (tarray t m) (v1 ++ v2) p.
