(* focus on the element i of an array of m elements *)
Lemma blkS_focus {cs: compspecs} sh T m (rows: list (reptype T)) p i :
  0 <= i < m -> Zlength rows = m ->
  data_at sh (tarray T m) rows p =
  array_at sh (tarray T m) [] 0 i (sublist 0 i rows) p *
  data_at sh T (Znth i rows) (field_address (tarray T m) [ArraySubsc i] p) *
  array_at sh (tarray T m) [] (i + 1) m (sublist (i + 1) m rows) p.
Proof.
  intros Hi Hl. unfold data_at at 1.
  erewrite field_at_Tarray; [| constructor | reflexivity | lia | apply JMeq_refl].
  erewrite (split3_array_at sh (tarray T m) [] 0 i m); [| lia | rewrite Z.sub_0_r; exact Hl | apply JMeq_refl].
  rewrite field_at_data_at. rewrite !Z.sub_0_r. reflexivity.
Qed.

Lemma blkS_unfocus {cs: compspecs} sh T m (rows: list (reptype T)) p i x :
  0 <= i < m -> Zlength rows = m ->
  array_at sh (tarray T m) [] 0 i (sublist 0 i rows) p *
  data_at sh T x (field_address (tarray T m) [ArraySubsc i] p) *
  array_at sh (tarray T m) [] (i + 1) m (sublist (i + 1) m rows) p
  |-- data_at sh (tarray T m) (upd_Znth i rows x) p.
Proof.
  intros Hi Hl.
  rewrite (blkS_focus sh T m (upd_Znth i rows x) p i) by (try rewrite Zlength_upd_Znth; lia).
  rewrite upd_Znth_same by lia.
  rewrite sublist_upd_Znth_l by lia. rewrite sublist_upd_Znth_r by lia. apply derives_refl.
Qed.

