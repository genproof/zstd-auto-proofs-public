(* Part of wb_misc (WB_misc.v): the bodies of within_oneshot and within_stream (harness/zlimits.h) in the writer
   units that have them.  Each unit's proof is in the generated src/proof/harness/<u>/WB_misc_within_<u>.v (template
   WB_misc_within, generated by a script that is not part of this repository; units without within_oneshot get an
   empty file); this file concludes from them. *)
Require Import VST.floyd.proofauto.
Require Zstd.proof.harness.stable_out.WSpecs_stable_out.
Require Zstd.proof.harness.valid_dict.WSpecs_valid_dict.
Require Zstd.proof.harness.valid_dict_copy.WSpecs_valid_dict_copy.
Require Zstd.proof.harness.valid_oneshot.WSpecs_valid_oneshot.
Require Zstd.proof.harness.valid_stream.WSpecs_valid_stream.
Require Zstd.proof.harness.stable_out.WB_misc_within_body_stable_out.
Require Zstd.proof.harness.valid_dict.WB_misc_within_body_valid_dict.
Require Zstd.proof.harness.valid_dict_copy.WB_misc_within_body_valid_dict_copy.
Require Zstd.proof.harness.valid_oneshot.WB_misc_within_body_valid_oneshot.
Require Zstd.proof.harness.valid_stream.WB_misc_within_body_valid_stream.

Theorem wb_misc_within :
  Zstd.proof.harness.stable_out.WSpecs_stable_out.body_within_oneshot /\
  Zstd.proof.harness.stable_out.WSpecs_stable_out.body_within_stream /\
  Zstd.proof.harness.valid_dict.WSpecs_valid_dict.body_within_oneshot /\
  Zstd.proof.harness.valid_dict_copy.WSpecs_valid_dict_copy.body_within_oneshot /\
  Zstd.proof.harness.valid_oneshot.WSpecs_valid_oneshot.body_within_oneshot /\
  Zstd.proof.harness.valid_stream.WSpecs_valid_stream.body_within_oneshot /\
  Zstd.proof.harness.valid_stream.WSpecs_valid_stream.body_within_stream.
Proof.
  exact (conj Zstd.proof.harness.stable_out.WB_misc_within_body_stable_out.wb_within_oneshot
        (conj Zstd.proof.harness.stable_out.WB_misc_within_body_stable_out.wb_within_stream
        (conj Zstd.proof.harness.valid_dict.WB_misc_within_body_valid_dict.wb_within_oneshot
        (conj Zstd.proof.harness.valid_dict_copy.WB_misc_within_body_valid_dict_copy.wb_within_oneshot
        (conj Zstd.proof.harness.valid_oneshot.WB_misc_within_body_valid_oneshot.wb_within_oneshot
        (conj Zstd.proof.harness.valid_stream.WB_misc_within_body_valid_stream.wb_within_oneshot
              Zstd.proof.harness.valid_stream.WB_misc_within_body_valid_stream.wb_within_stream)))))).
Qed.
