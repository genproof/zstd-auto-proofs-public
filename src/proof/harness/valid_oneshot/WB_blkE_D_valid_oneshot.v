Lemma blkD_borrow : forall {cs: compspecs} sh t n (d: Inhabitant (reptype t)) (al: list (reptype t)) p k,
  0 <= k < n -> Zlength al = n ->
  data_at sh (tarray t n) al p |--
  data_at sh t (@Znth (reptype t) d k al) (offset_val (sizeof t * k) p) *
  (data_at sh t (@Znth (reptype t) d k al) (offset_val (sizeof t * k) p) -* data_at sh (tarray t n) al p).
Proof.
  intros. eapply derives_trans; [apply (andp_right _ _ _ (data_at_local_facts sh (tarray t n) al p) (derives_refl _)) |].
  apply derives_extract_prop. intros [Hfc _].
  rewrite (blkD_split sh t n d al p k) by auto.
  apply sepcon_derives; [apply derives_refl |].
  apply wand_sepcon_adjoint. rewrite sepcon_comm. rewrite <- (blkD_split sh t n d al p k) by auto. apply derives_refl.
Qed.

Lemma blkD_borrow2 : forall {cs: compspecs} sh t m n (d1: Inhabitant (reptype (tarray t m))) (d2: Inhabitant (reptype t))
