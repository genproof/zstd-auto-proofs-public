(* the start of a segment proof: the segment's statements explicit (K stays abstract), Delta
   simplified as start_function does *)
Ltac blk_seg_start :=
  intros;
  lazymatch goal with |- semax _ _ ?s _ =>
    let s' := eval cbv [sq_with sq_drop blk_body f_w_compressed_block fn_body] in s in change s with s'
  end;
  unfold blk_Delta;
  simplify_func_tycontext;
  repeat match goal with |- context [Sloop (Ssequence (Sifthenelse ?e Sskip Sbreak) ?s) Sskip] =>
           fold (Swhile e s) end;
  abbreviate_semax.
