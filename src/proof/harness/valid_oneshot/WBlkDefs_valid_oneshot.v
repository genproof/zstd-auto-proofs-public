Definition seg_A : Prop :=
  forall (Espec: OracleKind) DC DD (E: blkenv) (K: statement) (R: ret_assert),
  blk_env_ok E ->
  semax (blk_Delta DC DD)
    (EX lm: Z, EX rleb: Z, EX Hl: whuf, blk_gen E lm rleb Hl [] [] [] (wt_rep (be_S E))) K R ->
  semax (blk_Delta DC DD) (blk_entry E) (sq_with 12 blk_body K) R.

Definition seg_B : Prop :=
  forall (Espec: OracleKind) DC DD (E: blkenv) (K: statement) (R: ret_assert)
    (lm rleb: Z) (Hl: whuf) (seqs: list sequence) (lits cont: list Z) (rep: Z * Z * Z),
  blk_env_ok E ->
  semax (blk_Delta DC DD)
    (EX seqs': list sequence, EX lits': list Z, EX cont': list Z, EX rep': Z * Z * Z,
       blk_gen E lm rleb Hl seqs' lits' cont' rep') K R ->
  semax (blk_Delta DC DD) (blk_gen E lm rleb Hl seqs lits cont rep) (sq_with 1 (sq_drop 12 blk_body) K) R.

Definition seg_C : Prop :=
  forall (Espec: OracleKind) DC DD (E: blkenv) (K: statement) (R: ret_assert)
    (lm rleb: Z) (Hl: whuf) (seqs: list sequence) (lits cont: list Z) (rep: Z * Z * Z),
  blk_env_ok E ->
  semax (blk_Delta DC DD) (EX trail: list Z, blk_trail E lm rleb Hl seqs lits cont trail rep) K R ->
  semax (blk_Delta DC DD) (blk_gen E lm rleb Hl seqs lits cont rep) (sq_with 1 (sq_drop 13 blk_body) K) R.

Definition seg_D : Prop :=
  forall (Espec: OracleKind) DC DD (E: blkenv) (K: statement) (R: ret_assert)
    (lm rleb: Z) (Hl: whuf) (seqs: list sequence) (lits cont trail: list Z) (rep: Z * Z * Z),
  blk_env_ok E ->
  semax (blk_Delta DC DD) (EX lb: list Z, blk_seqs E lm Hl seqs lits cont trail lb rep) K R ->
  semax (blk_Delta DC DD) (blk_trail E lm rleb Hl seqs lits cont trail rep) (sq_with 2 (sq_drop 14 blk_body) K) R.

Definition seg_E : Prop :=
  forall (Espec: OracleKind) DC DD (E: blkenv) (K: statement) (R: ret_assert)
