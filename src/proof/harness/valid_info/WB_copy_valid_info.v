   @data_at CompSpecs sh t_fse (Znth i l) (@field_address CompSpecs t_wstate (DOT _tab SUB i) p) *
   @array_at CompSpecs sh t_wstate (DOT _tab) (i + 1) 3 (sublist (i + 1) 3 l) p)%logic.
Proof.
  intros.
  erewrite field_at_Tarray; [ | | reflexivity | lia | apply JMeq_refl]; [ | split; [simpl; auto | compute; auto]].
  erewrite (split3seg_array_at sh t_wstate (DOT _tab) 0 i (i + 1) 3); [ | lia | lia | lia | ].
