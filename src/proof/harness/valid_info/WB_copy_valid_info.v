Lemma Znth_tc (t: type) (l: list val) (i: Z) :
  Forall vdef l -> Forall (tc_val' t) l -> 0 <= i < Zlength l -> tc_val t (Znth i l).
Proof.
  intros D F R.
  pose proof (proj1 (Forall_Znth _ _) D i R) as [x Hx].
  pose proof (proj1 (Forall_Znth _ _) F i R) as V.
  apply V. rewrite Hx; discriminate.
Qed.

Lemma cast_i2i_id sz sg v : tc_val (Tint sz sg noattr) v -> force_val (sem_cast_i2i sz sg v) = v.
Proof.
  destruct v; simpl; intros H; try contradiction.
  unfold cast_int_int; destruct sz, sg; simpl in H; f_equal;
    try change Byte.min_signed with (-128) in H; try change Byte.max_signed with 127 in H;
    try change Byte.max_unsigned with 255 in H;
    first [ apply sign_ext_inrange; simpl; lia
          | apply zero_ext_inrange; simpl; lia
          | reflexivity
          | destruct H; subst; reflexivity ].
Qed.

