      unfold bits_rep. rewrite F1, F2, F3, Efull.
      replace (Zlength (le_bytes (Z.to_nat (q + j)) (W + v * 2 ^ (8 * q + r))) -
               Zlength (le_bytes (Z.to_nat q) (W + v * 2 ^ (8 * q + r)))) with j
        by (rewrite !wb_len_le_bytes by lia; lia).
      replace (8 * q + r + nb - 8 * (q + j)) with (r + nb - 8 * j) by lia.
      unfold vl, vu. entailer!.
Qed.

